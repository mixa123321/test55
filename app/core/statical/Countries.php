    public static function getName($code)
    {
        return empty(self::$map[$code]) ? null : self::$map[$code];
    }

    public static function getCode($name)
    {
        if (empty(self::$flip_map)) {
            self::$flip_map = array_flip(array_map('mb_strtolower', self::$map));
            //self::$flip_map['united kingdom'] = 'GB';
        }

        return isset(self::$flip_map[mb_strtolower($name)]) ? self::$flip_map[mb_strtolower($name)] : '';
    }

    public static function getAll()
    {
        return self::$map;
    }

    public static function getNumber($code)
    {
        return empty(self::$numbers[$code]) ? null : self::$numbers[$code];
    }

    public static function getByNumber($number)
    {
        $map = array_flip(self::$numbers);
        return empty($map[$number]) ? null : $map[$number];
    }

    public static function getAlpha3($code)
    {
        return isset(self::$alpha3[$code]) ? self::$alpha3[$code] : '';
    }
